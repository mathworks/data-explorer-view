// Writes src/model/version.ts from package.json: VIEW_VERSION, this package's version, which an
// app shows in its About. A constant in the source rather than a read of package.json at run time:
// package.json is no export of the package, a page with no bundler cannot import JSON, and a
// bundler would put the whole file into the app for one field.
//
// With --check it writes nothing and fails when the committed module is not the one it would
// write: a version bumped in package.json and not here. `npm run build` is to run it first, as it
// runs gen-icon-assets.mjs. The constant is typed `string`, not the literal: the API check reads an
// export's type, and a literal would be a changed type at every release.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'model', 'version.ts');

const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
// Written into the module as a string literal, unescaped.
if (typeof version !== 'string' || !/^[\w.+-]+$/.test(version)) throw new Error(`package.json: ${JSON.stringify(version)} is not a version`);

const source = `// Copyright 2026 The MathWorks, Inc.
// GENERATED by scripts/gen-version.mjs from package.json. Do not edit.

/** This package's version, as its package.json says: what an app's About shows for data-explorer-view. */
export const VIEW_VERSION: string = '${version}';
`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(OUT, 'utf8');
  } catch {
    /* absent: not the module it would write */
  }
  if (committed !== source) {
    console.error(`${OUT} does not say package.json's version ${version}: run node scripts/gen-version.mjs`);
    process.exit(1);
  }
  console.log(`OK: ${OUT} says ${version}`);
} else {
  writeFileSync(OUT, source);
}
