// Writes src/widgets/icon-assets/assets.ts from icons/: one
// `new URL('<literal>', import.meta.url)` per icon, which is what a bundler (Vite, webpack 5,
// Parcel) recognises as an asset to copy into the app's build and rename. A literal per file,
// because a bundler resolves only a literal: a URL built from a variable is left alone, and the
// icon is not copied.
//
// `npm run build` runs this first, so dist/ is always built from the icons there are. With
// --check it writes nothing and fails when the committed module is not the one it would write.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'widgets', 'icon-assets', 'assets.ts');

const ids = readdirSync(join(ROOT, 'icons'))
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.slice(0, -'.svg'.length))
  .sort();

for (const id of ids) {
  // Every id is a key and a path segment, written into the module unescaped.
  if (!/^[\w-]+$/.test(id)) throw new Error(`icons/${id}.svg: an icon id is letters, digits, _ and - only`);
}

const source = `// Copyright 2026 The MathWorks, Inc.
// GENERATED by scripts/gen-icon-assets.mjs from icons/, by \`npm run build\`. Do not edit.
//
// Every icon's URL, each written as a literal \`new URL('../../../icons/<id>.svg', import.meta.url)\`
// so that a bundler copies the file into the app's build and puts its URL here. src/ and dist/ are
// both three folders below the package root.
export const ICON_ASSETS: Readonly<Record<string, string>> = {
${ids.map((id) => `  '${id}': new URL('../../../icons/${id}.svg', import.meta.url).href,`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(OUT, 'utf8');
  } catch {
    /* absent: not the module it would write */
  }
  if (committed !== source) {
    console.error(`${OUT} is not the module icons/ makes: run npm run build (or node scripts/gen-icon-assets.mjs)`);
    process.exit(1);
  }
  console.log(`OK: ${OUT} lists the ${ids.length} icons in icons/`);
} else {
  writeFileSync(OUT, source);
}
